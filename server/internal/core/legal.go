// Legal documents are articles of kind "legal" with a fixed slug. Admins edit them in the back office;
// changing the version of a required document asks every user to agree again on their next visit.
const (
	LegalTerms     = "terms"
	LegalPrivacy   = "privacy"
	LegalCopyright = "copyright"
	LegalAI        = "ai"
)

// RequiredLegal lists the documents people must accept to register and use the service.
var RequiredLegal = []string{LegalTerms, LegalPrivacy, LegalCopyright}

const legalSeedVersion = "2026-11-08"

type legalDoc struct {
	Slug, Title, Summary, Body string
	Order                      int
}

var defaultLegal = []legalDoc{
	{LegalTerms, "用户服务协议", "使用本平台前请仔细阅读", legalTermsBody, 1},
	{LegalPrivacy, "隐私政策", "我们如何收集、使用和保护你的信息", legalPrivacyBody, 2},
	{LegalCopyright, "版权与素材使用声明", "书稿、素材、声音的版权须由你自行确认", legalCopyrightBody, 3},
	{LegalAI, "AI 生成内容与声音使用规范", "AI 配音、声音克隆的使用规则", legalAIBody, 4},
}

// seedLegal creates any legal document that does not exist yet (existing ones are never overwritten).
func (a *App) seedLegal() {
	for _, d := range defaultLegal {
		var n int64
		a.DB.Model(&model.Article{}).Where("kind = ? AND slug = ?", "legal", d.Slug).Count(&n)
		if n > 0 {
			continue
		}
		a.DB.Create(&model.Article{Kind: "legal", Slug: d.Slug, Category: "协议与政策", Title: d.Title, Summary: d.Summary, Body: strings.TrimSpace(d.Body), Version: legalSeedVersion, SortOrder: d.Order, Published: true})
	}
}

// LegalDocs returns the published legal documents in display order.
func (a *App) LegalDocs() []model.Article {
	var list []model.Article
	a.DB.Where("kind = ? AND published = ?", "legal", true).Order("sort_order asc").Find(&list)
	return list
}

// LegalVersion identifies the current set of required documents; it changes whenever an admin publishes a
// new version of any of them.
func (a *App) LegalVersion() string {
	var parts []string
	for _, slug := range RequiredLegal {
		var d model.Article
		if a.DB.Select("version").First(&d, "kind = ? AND slug = ? AND published = ?", "legal", slug, true).Error == nil {
			parts = append(parts, slug+":"+d.Version)
		}
	}
	return strings.Join(parts, ";")
}

// AgreeLegal records that the user accepted the current documents.
func (a *App) AgreeLegal(userID string) string {
	v := a.LegalVersion()
	t := time.Now()
	a.DB.Model(&model.User{}).Where("id = ?", userID).Updates(map[string]any{"legal_version": v, "legal_agreed_at": &t})
	return v
}

// RenderLegal fills the operator details from the site settings into a document body.
func (a *App) RenderLegal(body string) string {
	site := a.Site()
	name := firstNonEmpty(site.Name, "本平台")
	op := firstNonEmpty(site.Operator, name+"运营方")
	mail := firstNonEmpty(site.SupportEmail, "平台公布的客服渠道")
	return strings.NewReplacer("{平台名称}", name, "{运营主体}", op, "{联系邮箱}", mail).Replace(body)
}

